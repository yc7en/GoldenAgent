export function ToolIcon({ name, ...props }: { name: string } & IconProps) {
  switch (name) {
    case "bash":
      return <CommandLineIcon {...props} />;
    case "read_file":
      return <DocumentTextIcon {...props} />;
    case "write_file":
      return <PencilSquareIcon {...props} />;
    case "apply_patch":
      return <CodeBracketIcon {...props} />;
    case "list_dir":
      return <FolderIcon {...props} />;
    case "grep":
      return <MagnifyingGlassIcon {...props} />;
    case "glob":
      return <DocumentMagnifyingGlassIcon {...props} />;
    case "use_skill":
      return <AcademicCapIcon {...props} />;
    case "invoke_subagent":
      return <CpuChipIcon {...props} />;
    default:
      return <WrenchScrewdriverIcon {...props} />;
  }
}
